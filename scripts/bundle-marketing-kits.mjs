import { readFileSync, writeFileSync, readdirSync } from 'node:fs';
import { join, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';
import { ALL_APP_IDS } from '../functions/lib/packs.js';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const kitsDir = join(root, 'marketing-kits');
const outFile = join(root, 'functions/lib/marketing-kit-content.js');

const files = readdirSync(kitsDir).filter((f) => f.endsWith('.html'));
const map = {};
for (const file of files) {
  const appId = file.replace(/\.html$/, '');
  map[appId] = readFileSync(join(kitsDir, file), 'utf8');
}

const missing = ALL_APP_IDS.filter((id) => !map[id]);
const extra = Object.keys(map).filter((id) => !ALL_APP_IDS.includes(id));
if (missing.length) {
  console.error('Missing kits for:', missing.join(', '));
  process.exit(1);
}
if (extra.length) {
  console.warn('Extra kit files (ignored in output):', extra.join(', '));
}

const body = `// AUTO-GENERATED by scripts/bundle-marketing-kits.mjs — do not edit by hand.
export const MARKETING_KIT_HTML = ${JSON.stringify(
  Object.fromEntries(ALL_APP_IDS.map((id) => [id, map[id]])),
)};
`;
writeFileSync(outFile, body, 'utf8');
console.log('Wrote', outFile, '—', ALL_APP_IDS.length, 'kits');